def load_documents():
    """Return summary of all saved documents."""
    init_table()
    with _conn() as conn:
        return pd.read_sql(
            """
            SELECT DOC_ID, FILENAME, VERSION_LABEL, UPLOADED_AT, N_INSTRUMENTS
            FROM (
                SELECT DOC_ID,
                       MAX(FILENAME)      AS FILENAME,
                       MAX(VERSION_LABEL) AS VERSION_LABEL,
                       MAX(UPLOADED_AT)   AS UPLOADED_AT,
                       COUNT(*)           AS N_INSTRUMENTS
                FROM   CAD_DATA
                GROUP  BY DOC_ID
            )
            ORDER BY UPLOADED_AT DESC
            """,
            conn,
        )


def load_instruments(doc_id):
    """Return all instrument rows for one document."""
    init_table()
    with _conn() as conn:
        df = pd.read_sql(
            """
            SELECT FUNC, SYSTEM_CODE, COMPONENT_ID, PIPE_SIZES,
                   CONFIDENCE, X, Y, W, H
            FROM   CAD_DATA
            WHERE  DOC_ID = :1
            ORDER  BY Y, X
            """,
            conn, params=[int(doc_id)],
        )
    # Lowercase columns for the diff module
    df.columns = [c.lower() for c in df.columns]
    return df



def load_detections(doc_id):
    """Return all raw detections for one document, sorted by position."""
    init_table()
    with _conn() as conn:
        df = pd.read_sql(
            "SELECT TEXT_RAW, TEXT_NORM, CATEGORY, CONFIDENCE, SOURCE, "
            "       X, Y, W, H "
            "FROM   CAD_DETECTIONS "
            "WHERE  DOC_ID = :1 "
            "ORDER  BY Y, X",
            conn, params=[int(doc_id)],
        )
    return df



def delete_document(doc_id):
    init_table()
    with _conn() as conn:
        cur = conn.cursor()
        cur.execute("DELETE FROM CAD_DATA WHERE DOC_ID = :1", [int(doc_id)])
        conn.commit()


def save_render(doc_id, image):
    """
    Save the rendered page as PNG for visual diff.
    The image should be the ORIGINAL rendered image (not preprocessed).
    """
    from PIL import Image
    import numpy as np
    import pathlib

    render_dir = pathlib.Path("output/renders")
    render_dir.mkdir(parents=True, exist_ok=True)
    path = render_dir / f"doc_{int(doc_id)}.png"

    if isinstance(image, np.ndarray):
        # If shape is (H, W, 3), assume RGB (PIL-format array, not BGR)
        if image.ndim == 3 and image.shape[2] == 3:
            img = Image.fromarray(image.astype(np.uint8))
        elif image.ndim == 2:
            img = Image.fromarray(image.astype(np.uint8)).convert("RGB")
        else:
            raise ValueError(f"Unsupported image shape: {image.shape}")
    elif isinstance(image, Image.Image):
        img = image.convert("RGB")
    else:
        raise ValueError("Unsupported image type")

    img.save(path)
    print(f"[ORACLE] Saved render for doc {doc_id}: {path}  size={img.size}")
    return str(path)


def get_render_path(doc_id):
    """Return PNG path for a document, or None if it doesn't exist."""
    import pathlib
    path = pathlib.Path("output/renders") / f"doc_{int(doc_id)}.png"
    return str(path) if path.exists() else None


def get_document_page_size(doc_id):
    """Return (page_width, page_height) for a document, or (None, None) if missing."""
    init_table()
    with _conn() as conn:
        cur = conn.cursor()
        cur.execute(
            "SELECT MAX(PAGE_WIDTH), MAX(PAGE_HEIGHT) "
            "FROM CAD_DATA WHERE DOC_ID = :d",
            d=int(doc_id),
        )
        row = cur.fetchone()
    if not row or row[0] is None:
        return (None, None)
    return (int(row[0]), int(row[1]))